using Microsoft.Data.SqlClient;
using VetCare.Helpers;
using VetCare.Models;
using VetCare.Models.Entities;
using VetCare.Models.Repositories;
using VetCare.Views.Admin;
using VetCare.Views.Controls;
using VetCare.Views.Shared;

namespace VetCare.Controllers;

/// <summary>
/// Reports (Tasks/VetCare_Reports_Module.md, section 4):
///  1. only the Administrator opens Reports;  2. filtered by the clinic;  3. read-only;
///  4. a date range is required, the end can't be before the start, at most 1 year;
///  5. archived records aren't counted; voided bills only appear in the Voided bills report;
///  6. Daily collection = money received (Payment), Income summary = amounts billed (BillItem);
///  7. no-show rate = no-shows ÷ (completed + no-shows) × 100;  8. stock value = stock × price, value lost = qty × price;
///  9. ₱ with 2 decimals, local dates;  10. exports and printouts show who generated the report and when.
/// </summary>
public sealed class ReportController
{
    private const string DatabaseError = "Can’t reach the VetCare database. Check your connection and try again.";

    private readonly UserSession _session;
    private readonly ReportRepository _reports;
    private readonly ClinicRepository _clinics;
    private readonly DashboardRepository _dashboard = new();

    private ModuleHostView _host;
    private ReportsPage _home;
    private Toast _toast;
    private DateTime _from, _to;
    private ReportPeriod _period = ReportPeriod.ThisMonth;
    private List<(int Id, string Name)> _vets, _cashiers;

    public ReportController(UserSession session, ReportRepository reports, ClinicRepository clinics)
    {
        _session = session;
        _reports = reports;
        _clinics = clinics;
        (_from, _to) = DateRangeHelper.RangeOf(_period, DateTime.Today);
    }

    /// <summary>Rule 1.</summary>
    public bool CanView => _session.ClinicId != null && _session.IsAdministrator;

    private int ClinicId => _session.ClinicId ?? 0;

    /// <summary>"Generated by Ana Reyes (Administrator) on Nov 18, 2026, 7:30 AM" (rule 10).</summary>
    public string GeneratedBy(DateTime when) =>
        "Generated by " + _session.FullName + " (" + _session.RoleName + ") on " + when.ToString("MMM d, yyyy, h:mm tt", System.Globalization.CultureInfo.InvariantCulture);

    // Data methods (section 6) ----------------------------------------------------------------------------------------

    public Task<ReportQuickLook> GetQuickLookAsync(DateTime from, DateTime to) => _reports.GetQuickLookAsync(ClinicId, from, to, DateTime.Today);

    public Task<ReportResult> GetAppointmentSummaryAsync(ReportFilters f) => _reports.AppointmentSummaryAsync(ClinicId, f);
    public Task<ReportResult> GetNoShowReportAsync(ReportFilters f) => _reports.NoShowAsync(ClinicId, f);
    public Task<ReportResult> GetVetWorkloadAsync(ReportFilters f) => _reports.VetWorkloadAsync(ClinicId, f);
    public Task<ReportResult> GetVisitReasonsAsync(ReportFilters f) => _reports.VisitReasonsAsync(ClinicId, f);
    public Task<ReportResult> GetGuestBookingReportAsync(ReportFilters f) => _reports.GuestBookingsAsync(ClinicId, f);
    public Task<ReportResult> GetConsultationSummaryAsync(ReportFilters f) => _reports.ConsultationSummaryAsync(ClinicId, f);
    public Task<ReportResult> GetPatientReportAsync(ReportFilters f) => _reports.PatientReportAsync(ClinicId, f);
    public Task<ReportResult> GetVaccinationReportAsync(ReportFilters f) => _reports.VaccinationReportAsync(ClinicId, f);
    public Task<ReportResult> GetOverdueVaccinesAsync(ReportFilters f) => _reports.OverdueVaccinesAsync(ClinicId, f, DateTime.Today);
    public Task<ReportResult> GetStockLevelsAsync(ReportFilters f) => _reports.StockLevelsAsync(ClinicId, f, DateTime.Today);
    public Task<ReportResult> GetStockMovementAsync(ReportFilters f) => _reports.StockMovementAsync(ClinicId, f);
    public Task<ReportResult> GetMedicineUsageAsync(ReportFilters f) => _reports.MedicineUsageAsync(ClinicId, f);
    public Task<ReportResult> GetExpiredDamagedAsync(ReportFilters f) => _reports.ExpiredDamagedAsync(ClinicId, f);
    public Task<ReportResult> GetDailyCollectionAsync(ReportFilters f) => _reports.DailyCollectionAsync(ClinicId, f);
    public Task<ReportResult> GetIncomeSummaryAsync(ReportFilters f) => _reports.IncomeSummaryAsync(ClinicId, f);
    public Task<ReportResult> GetOutstandingBalancesAsync(ReportFilters f) => _reports.OutstandingAsync(ClinicId, f, DateTime.Today);
    public Task<ReportResult> GetVoidedBillsAsync(ReportFilters f) => _reports.VoidedBillsAsync(ClinicId, f);

    /// <summary>Rules 1 and 4, then the report's query. Returns the date problem instead when the range is invalid.</summary>
    public async Task<(ReportResult Result, string DateProblem)> GenerateAsync(ReportType type, ReportFilters f)
    {
        if (!CanView) return (null, "Only the Administrator can open reports.");
        string problem = DateRangeHelper.Problem(f.From, f.To);
        if (problem != null) return (null, problem);

        var result = type switch
        {
            ReportType.AppointmentSummary => await GetAppointmentSummaryAsync(f),
            ReportType.NoShowCancellation => await GetNoShowReportAsync(f),
            ReportType.VetWorkload => await GetVetWorkloadAsync(f),
            ReportType.VisitReasons => await GetVisitReasonsAsync(f),
            ReportType.GuestBookings => await GetGuestBookingReportAsync(f),
            ReportType.ConsultationSummary => await GetConsultationSummaryAsync(f),
            ReportType.PatientReport => await GetPatientReportAsync(f),
            ReportType.VaccinationReport => await GetVaccinationReportAsync(f),
            ReportType.OverdueVaccines => await GetOverdueVaccinesAsync(f),
            ReportType.StockLevels => await GetStockLevelsAsync(f),
            ReportType.StockMovement => await GetStockMovementAsync(f),
            ReportType.MedicineUsage => await GetMedicineUsageAsync(f),
            ReportType.ExpiredDamaged => await GetExpiredDamagedAsync(f),
            ReportType.DailyCollection => await GetDailyCollectionAsync(f),
            ReportType.IncomeSummary => await GetIncomeSummaryAsync(f),
            ReportType.OutstandingBalances => await GetOutstandingBalancesAsync(f),
            _ => await GetVoidedBillsAsync(f)
        };
        return (new ReportResult
        {
            Definition = ReportCatalog.For(type),
            Filters = f,
            Cards = result.Cards,
            Chart = result.Chart,
            SideChart = result.SideChart,
            TableTitle = result.TableTitle,
            Columns = result.Columns,
            Rows = result.Rows,
            Total = result.Total,
            Note = result.Note
        }, null);
    }

    // View --------------------------------------------------------------------------------------------------------------

    public View CreateView()
    {
        if (!CanView)
            return new Label
            {
                Text = "Reports are available to the clinic Administrator.",
                FontSize = 16,
                TextColor = ThemeResources.Color("BodyText"),
                Margin = new Thickness(40)
            };

        _host = new ModuleHostView();
        _host.Dialog.CancelRequested += async (s, e) => await _host.Dialog.HideAsync();
        _host.Dialog.Confirmed += async (s, e) => await _host.Dialog.HideAsync();

        _home = new ReportsPage(_period, _from, _to);
        _home.PeriodChanged += async (s, e) => { (_period, _from, _to) = (e.Period, e.From, e.To); await LoadQuickLookAsync(); };
        _home.ReportRequested += async (s, type) => await OpenReportAsync(type);
        _host.ShowPage(_home);
        _toast = new Toast();
        _ = LoadQuickLookAsync();
        return new Grid { Children = { _host, _toast } };
    }

    private async Task LoadQuickLookAsync()
    {
        try
        {
            _home.ShowQuickLook(await GetQuickLookAsync(_from, _to));
        }
        catch (SqlException)
        {
            _home.ShowQuickLookError(DatabaseError);
        }
    }

    private async Task OpenReportAsync(ReportType type)
    {
        var definition = ReportCatalog.For(type);
        try
        {
            if (definition.Filters.HasFlag(ReportFilter.Vet)) _vets ??= await _reports.GetPeopleAsync(ClinicId, RoleIds.Veterinarian);
            if (definition.Filters.HasFlag(ReportFilter.Cashier)) _cashiers ??= await _reports.GetPeopleAsync(ClinicId, RoleIds.CashierStaff);
        }
        catch (SqlException) { /* the filters stay at "All"; Generate shows the error */ }

        var viewer = new ReportViewerPage(definition, _from, _to, _vets, _cashiers);
        viewer.BackRequested += async (s, e) => { _host.ShowPage(_home); await LoadQuickLookAsync(); };
        viewer.GenerateRequested += async (s, e) => await GenerateIntoAsync(viewer);
        viewer.PrintRequested += async (s, e) => await ExportAsync(viewer, ExportKind.Print);
        viewer.PdfRequested += async (s, e) => await ExportAsync(viewer, ExportKind.Pdf);
        viewer.ExcelRequested += async (s, e) => await ExportAsync(viewer, ExportKind.Excel);
        _host.ShowPage(viewer);
        await GenerateIntoAsync(viewer);
    }

    private async Task GenerateIntoAsync(ReportViewerPage viewer)
    {
        var filters = viewer.ReadFilters(out string dateProblem);
        if (dateProblem != null) { viewer.ShowDateError(dateProblem); return; }
        viewer.ShowLoading();
        var sync = await _dashboard.GetSyncStateAsync(ClinicId);
        try
        {
            var (result, problem) = await GenerateAsync(viewer.Definition.Type, filters);
            if (problem != null) { viewer.ShowDateError(problem); return; }
            viewer.Show(result, sync, GeneratedBy(DateTime.Now));
        }
        catch (SqlException)
        {
            viewer.ShowError(sync.Online ? DatabaseError : "You're offline. " + DatabaseError);
        }
    }

    // Print / export (section 3.C) -----------------------------------------------------------------------------------------

    private enum ExportKind { Print, Pdf, Excel }

    private async Task ExportAsync(ReportViewerPage viewer, ExportKind kind)
    {
        var result = viewer.Result;
        if (result == null) return;
        try
        {
            var clinic = await _clinics.GetByIdAsync(ClinicId);
            string generated = GeneratedBy(DateTime.Now);
            string name = ExportHelper.FileName(result);
            string path;
            if (kind == ExportKind.Print)
            {
                path = Path.Combine(FileSystem.CacheDirectory, name + ".html");
                await File.WriteAllTextAsync(path, ReportPrintDocument.Build(result, clinic, generated));
            }
            else
            {
                string folder = ExportHelper.ExportFolder();
                path = Path.Combine(folder, name + (kind == ExportKind.Pdf ? ".pdf" : ".xlsx"));
                await Task.Run(() =>
                {
                    if (kind == ExportKind.Pdf) ExportHelper.WritePdf(path, result, clinic, generated);
                    else ExportHelper.WriteExcel(path, result, clinic, generated);
                });
                _toast.Show("Saved to Documents\\VetCare Reports\\" + Path.GetFileName(path));
            }
            await Launcher.Default.OpenAsync(new OpenFileRequest(kind == ExportKind.Print ? "Print" : "Open", new ReadOnlyFile(path)));
        }
        catch (SqlException)
        {
            await ShowInfoAsync("Can’t export right now", DatabaseError);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            await ShowInfoAsync("Can’t save the file", "Close the file if it's open in another program, then try again. (" + ex.Message + ")");
        }
    }

    private Task ShowInfoAsync(string title, string message) =>
        _host.Dialog.ShowConfirmAsync(title, message, "OK", danger: false, icon: "circle-alert", showCancel: false);
}
